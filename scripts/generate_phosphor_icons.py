"""Regenerate the small, pinned Phosphor Compose subset without network access."""
from pathlib import Path
import argparse
import hashlib
import json
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / 'sharedUi/src/commonMain/phosphor'
KOTLIN = ROOT / 'sharedUi/src/commonMain/kotlin/com/music/bitchord/ui/icons'
NOTICE = ROOT / 'sharedUi/src/commonMain/composeResources/files/Phosphor-MIT.txt'


def pascal(name):
    return ''.join(part.title() for part in name.split('-'))


def outputs():
    manifest = json.loads((VENDOR / 'provenance.json').read_text(encoding='utf-8'))
    icons = manifest['icons']
    assets = {}
    for asset in manifest['assets']:
        data = (VENDOR / asset['path']).read_bytes()
        assert hashlib.sha256(data).hexdigest() == asset['sha256'], asset['path']
        blob = hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest()
        assert blob == asset['git_blob'], asset['path']
        svg = ET.fromstring(data)
        assert svg.attrib == {'viewBox': '0 0 256 256', 'fill': 'currentColor'}, asset['path']
        paths = []
        for node in svg:
            assert node.tag.endswith('}path') and set(node.attrib) == {'d'}, asset['path']
            paths.append(node.attrib['d'])
        assert paths, asset['path']
        assets[asset['path']] = paths
    source = [
        '// Generated by scripts/generate_phosphor_icons.py; edit the pinned SVG subset and manifest.',
        '// Phosphor Icons, Copyright (c) 2023 Phosphor Icons. MIT; see Phosphor-MIT.txt.',
        'package com.music.bitchord.ui.icons', '',
        'import androidx.compose.ui.graphics.Color',
        'import androidx.compose.ui.graphics.SolidColor',
        'import androidx.compose.ui.graphics.vector.ImageVector',
        'import androidx.compose.ui.graphics.vector.PathParser',
        'import androidx.compose.ui.unit.dp', '',
        'internal object PhosphorVectors {',
    ]
    identifiers = {}
    for semantic, icon in icons.items():
        assert icon['weight'] in ('regular', 'fill'), semantic
        key = (icon['name'], icon['weight'], icon['auto_mirror'])
        identifiers[semantic] = pascal(icon['name']) + icon['weight'].title() + ('Mirrored' if icon['auto_mirror'] else '')
    for name, weight, mirrored in sorted({(v['name'], v['weight'], v['auto_mirror']) for v in icons.values()}):
        path = f'assets/{weight}/{name}' + ('-fill' if weight == 'fill' else '') + '.svg'
        identifier = pascal(name) + weight.title() + ('Mirrored' if mirrored else '')
        source += [f'    val {identifier}: ImageVector by lazy {{',
                   f'        ImageVector.Builder(name = "Phosphor.{weight}.{name}",',
                   '            defaultWidth = 24.dp, defaultHeight = 24.dp,',
                   f'            viewportWidth = 256f, viewportHeight = 256f, autoMirror = {str(mirrored).lower()},',
                   '        ).apply {']
        for path_data in assets[path]:
            source += ['            addPath(',
                       '                pathData = PathParser().parsePathString(' + json.dumps(path_data) + ').toNodes(),',
                       '                fill = SolidColor(Color.Black),',
                       '            )']
        source += ['        }.build()', '    }', '']
    source += ['}', '']
    facade = [
        'package com.music.bitchord.ui.icons', '',
        'import androidx.compose.ui.graphics.vector.ImageVector', '',
        '/** Semantic icons shared by Android and TV; only Phosphor Regular and Fill are used. */',
        'object AppIcons {',
    ]
    facade += [f'    val {name}: ImageVector get() = PhosphorVectors.{identifier}' for name, identifier in identifiers.items()]
    facade += ['}', '']
    license_data = (VENDOR / 'LICENSE').read_bytes()
    assert hashlib.sha256(license_data).hexdigest() == manifest['license_sha256']
    return {KOTLIN / 'PhosphorVectors.kt': '\n'.join(source).encode(),
            KOTLIN / 'AppIcons.kt': '\n'.join(facade).encode(), NOTICE: license_data}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = outputs()
    for path, data in generated.items():
        if args.check:
            assert path.is_file() and path.read_bytes() == data, f'Regenerate {path.relative_to(ROOT)}'
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f'Phosphor subset: {len(generated)} generated files verified' if args.check else
          f'Phosphor subset: generated {len(generated)} files')


if __name__ == '__main__':
    main()
